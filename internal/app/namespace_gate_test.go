// TestListApplicationsGateKeepsRenderedSiblings is the review repro: an
// Application renders a chart whose single template declares an
// ApplicationSet in a namespace that Argo CD does not reconcile and an
// Application in the argocd namespace. Every rendered object gets the same
// file and document index, so the gate must not remove the Application
// with the ApplicationSet.
func TestListApplicationsGateKeepsRenderedSiblings(t *testing.T) {
	root := t.TempDir()
	writeTestFile(t, filepath.Join(root, "settings", "cm.yaml"), "apiVersion: v1\nkind: ConfigMap\nmetadata:\n  name: argocd-cmd-params-cm\n  namespace: argocd\ndata:\n  application.namespaces: \"\"\n")
	writeTestFile(t, filepath.Join(root, "root", "parent.yaml"), strings.NewReplacer("NAMESPACE", "argocd", "NAME", "parent", "workloads/demo", "children").Replace(namespaceGateApplicationTemplate))
	writeTestFile(t, filepath.Join(root, "children", "Chart.yaml"), "apiVersion: v2\nname: children\nversion: 0.1.0\n")
	writeTestFile(t, filepath.Join(root, "children", "templates", "apps.yaml"), `apiVersion: argoproj.io/v1alpha1
kind: ApplicationSet
metadata:
  name: disabled-set
  namespace: team-x
spec:
  generators:
  - list:
      elements:
      - name: a
  template:
    metadata:
      name: 'gen-{{`+"`"+`{{name}}`+"`"+`}}'
    spec:
      project: default
      source:
        repoURL: https://example.test/repo.git
        targetRevision: HEAD
        path: workloads/demo
      destination:
        server: https://kubernetes.default.svc
        namespace: x
---
`+strings.NewReplacer("NAMESPACE", "argocd", "NAME", "child-ok").Replace(namespaceGateApplicationTemplate))
	writeTestFile(t, filepath.Join(root, "workloads", "demo", "cm.yaml"), "apiVersion: v1\nkind: ConfigMap\nmetadata:\n  name: demo\n")
	names, warnings := listedApplications(t, root)
	if got, want := strings.Join(names, ","), "argocd/child-ok,argocd/parent"; got != want {
		t.Fatalf("Applications = %s, want %s", got, want)
	}
	if len(warnings) != 1 || !strings.Contains(warnings[0], "ApplicationSet team-x/disabled-set is skipped") {
		t.Fatalf("namespace warnings = %q, want one for team-x/disabled-set", warnings)
	}
}

// TestListApplicationsGateKeepsListSiblings pins the same rule for the items
// of one kind: List, which share a file and a document index.
func TestListApplicationsGateKeepsListSiblings(t *testing.T) {
	root := t.TempDir()
	writeTestFile(t, filepath.Join(root, "settings", "cm.yaml"), "apiVersion: v1\nkind: ConfigMap\nmetadata:\n  name: argocd-cmd-params-cm\n  namespace: argocd\n")
	indent := func(text string) string {
		lines := strings.Split(strings.TrimRight(text, "\n"), "\n")
		for i, line := range lines {
			prefix := "    "
			if i == 0 {
				prefix = "  - "
			}
			lines[i] = prefix + line
		}
		return strings.Join(lines, "\n") + "\n"
	}
	appSet := strings.Replace(namespaceGateApplicationSet, "namespace: team-a", "namespace: team-x", 1)
	app := strings.NewReplacer("NAMESPACE", "argocd", "NAME", "list-ok").Replace(namespaceGateApplicationTemplate)
	writeTestFile(t, filepath.Join(root, "apps", "list.yaml"), "apiVersion: v1\nkind: List\nitems:\n"+indent(appSet)+indent(app))
	writeTestFile(t, filepath.Join(root, "workloads", "demo", "cm.yaml"), "apiVersion: v1\nkind: ConfigMap\nmetadata:\n  name: demo\n")
	names, warnings := listedApplications(t, root)
	if got, want := strings.Join(names, ","), "argocd/list-ok"; got != want {
		t.Fatalf("Applications = %s, want %s", got, want)
	}
	if len(warnings) != 1 || !strings.Contains(warnings[0], "ApplicationSet team-x/tenant-set is skipped") {
		t.Fatalf("namespace warnings = %q, want one for team-x/tenant-set", warnings)
	}
}

// TestListApplicationsKeepsEveryNamespaceWhenTheConfigMapNamesNone is the
// review repro: a committed argocd-cmd-params-cm without metadata.namespace,
// which a kustomization puts in the gitops namespace. drydock cannot tell
// the controller namespace, so it must keep the gitops Application.
func TestListApplicationsKeepsEveryNamespaceWhenTheConfigMapNamesNone(t *testing.T) {
	root := t.TempDir()
	writeTestFile(t, filepath.Join(root, "argocd", "kustomization.yaml"), "apiVersion: kustomize.config.k8s.io/v1beta1\nkind: Kustomization\nnamespace: gitops\nresources:\n- argocd-cmd-params-cm.yaml\n")
	writeTestFile(t, filepath.Join(root, "argocd", "argocd-cmd-params-cm.yaml"), "apiVersion: v1\nkind: ConfigMap\nmetadata:\n  name: argocd-cmd-params-cm\ndata:\n  server.insecure: \"true\"\n")
	writeTestFile(t, filepath.Join(root, "apps", "app.yaml"), strings.NewReplacer("NAMESPACE", "gitops", "NAME", "myapp").Replace(namespaceGateApplicationTemplate))
	writeTestFile(t, filepath.Join(root, "workloads", "demo", "cm.yaml"), "apiVersion: v1\nkind: ConfigMap\nmetadata:\n  name: demo\n")
	names, warnings := listedApplications(t, root)
	if got, want := strings.Join(names, ","), "gitops/myapp"; got != want {
		t.Fatalf("Applications = %s, want %s", got, want)
	}
	if len(warnings) != 0 {
		t.Fatalf("namespace warnings = %q, want none", warnings)
	}
}
